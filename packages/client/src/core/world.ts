/**
 * Признак «игрок в мире».
 *
 * Вынесен в отдельный модуль, а не оставлен в точке входа, потому что от
 * него зависит блокировка управления в render-обработчике: пока игрок на
 * экране входа, ввод не должен доходить до игры (иначе он «печатает» и
 * одновременно бежит вперёд).
 */

let inWorld = false;

export const setInWorld = (value: boolean): void => {
  inWorld = value;
};

export const isInWorld = (): boolean => inWorld;
